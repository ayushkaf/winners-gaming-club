// site/build.js — bundles the REAL engine modules (unmodified sources) into a
// classic browser script, and injects the tuned config + validation summary.
// The site therefore runs exactly the code the Monte Carlo validation ran.
//
//   node site/build.js  ->  site/engine.js

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const FILES = [
  'core/prng.js',
  'core/lines.js',
  'core/coins.js',
  'core/engine.js',
  'models/modelA.js',
  'models/modelB.js',
];

function bundleFile(rel) {
  const src = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  const names = [];
  for (const m of src.matchAll(/^export (?:const|function|let) (\w+)/gm)) names.push(m[1]);
  let code = src
    .replace(/^import\s*\{([^}]+)\}\s*from\s*['"][^'"]+['"];\s*$/gm, 'const {$1} = __T;')
    .replace(/^export /gm, '');
  return `// ==== ${rel} ====\n(function () {\n${code}\nObject.assign(__T, { ${names.join(', ')} });\n})();\n`;
}

let out = `// site/engine.js — GENERATED by site/build.js. Do not edit by hand.\n`;
out += `// Contains the exact core/model sources used by the Node simulator.\n`;
out += `'use strict';\nconst __T = {};\n`;
for (const f of FILES) out += bundleFile(f);

const tuned = fs.readFileSync(path.join(ROOT, 'config', 'tuned.json'), 'utf8');
out += `__T.TUNED = ${tuned.trim()};\n`;
try {
  const summary = fs.readFileSync(path.join(ROOT, 'config', 'validation_summary.json'), 'utf8');
  out += `__T.SUMMARY = ${summary.trim()};\n`;
} catch {
  out += `__T.SUMMARY = null;\n`;
}
out += `globalThis.TORO = __T;\n`;

fs.writeFileSync(path.join(ROOT, 'site', 'engine.js'), out);
console.log(`site/engine.js written (${(out.length / 1024).toFixed(1)} KB)`);
